util::Result<bool>
RpcClient::proc_exists(const std::string& name) {
    auto packed = rpc_serial::pack_string(name);
    auto result = send_and_recv(
        static_cast<std::uint8_t>(RpcOpcode::ProcExists),
        packed.data(), packed.size());

    if (!result) return result.error();

    auto unpacked = rpc_serial::unpack_u32(*result);
    if (!unpacked) return unpacked.error();
    return *unpacked != 0;
}


// -- Stream operations -------------------------------------------------------

util::Result<std::uint32_t>
RpcClient::open_data_stream(const std::string& func_name,
                             const std::vector<std::vector<std::uint8_t>>& params) {
    std::vector<std::uint8_t> payload;
    std::uint8_t name_len = static_cast<std::uint8_t>(
        std::min(func_name.size(), static_cast<std::size_t>(255)));
    payload.push_back(name_len);
    payload.insert(payload.end(), func_name.begin(),
                   func_name.begin() + name_len);

    auto packed_params = rpc_serial::pack_params(params);
    payload.insert(payload.end(), packed_params.begin(), packed_params.end());

    auto result = send_and_recv(
        static_cast<std::uint8_t>(RpcOpcode::StreamOpen),
        payload.data(), payload.size());

    if (!result) return result.error();

    auto stream_id = rpc_serial::unpack_u32(*result);
    if (!stream_id) return stream_id.error();
    return *stream_id;
}

util::Result<std::uint32_t>
RpcClient::open_item_stream(const std::string& func_name,
                             const std::vector<std::vector<std::uint8_t>>& params) {
    // Same as data stream, just a different type flag
    return open_data_stream(func_name, params);
}

util::Result<std::vector<std::uint8_t>>
RpcClient::get_stream_data(std::uint32_t stream_id) {
    auto packed = rpc_serial::pack_u32(stream_id);
    auto result = send_and_recv(
        static_cast<std::uint8_t>(RpcOpcode::StreamData),
        packed.data(), packed.size());

    return result;
}

util::Result<void>
RpcClient::close_stream(std::uint32_t stream_id) {
    auto packed = rpc_serial::pack_u32(stream_id);
    auto result = send_and_recv(
        static_cast<std::uint8_t>(RpcOpcode::StreamClose),
        packed.data(), packed.size());

    if (!result) return result.error();
    return util::Ok();
}


// -- Internal ----------------------------------------------------------------

util::Result<std::vector<std::uint8_t>>
RpcClient::send_and_recv(std::uint8_t opcode, const void* data,
                          std::size_t len) {
    std::lock_guard<std::mutex> lock(mu_);

    // Build frame: [4-byte BE length][opcode][payload]
    std::uint32_t payload_len = static_cast<std::uint32_t>(1 + len);
    std::vector<std::uint8_t> frame(4 + 1 + len);

    // Big-endian length
    frame[0] = static_cast<std::uint8_t>((payload_len >> 24) & 0xFF);
    frame[1] = static_cast<std::uint8_t>((payload_len >> 16) & 0xFF);
    frame[2] = static_cast<std::uint8_t>((payload_len >> 8) & 0xFF);
    frame[3] = static_cast<std::uint8_t>(payload_len & 0xFF);

    // Opcode
    frame[4] = opcode;

    // Payload
    if (len > 0 && data) {
        std::memcpy(frame.data() + 5, data, len);
    }

    auto sent = transport_->send(frame.data(), frame.size());
    if (!sent) return sent.error();

    // Read reply header: [4-byte BE length]
    std::uint8_t hdr[4];
    std::size_t got = 0;
    while (got < 4) {
        auto n = transport_->recv(hdr + got, 4 - got);
        if (!n) return n.error();
        if (*n == 0) return util::Error{23, "connection closed"};
        got += *n;
    }

    std::uint32_t reply_len = (static_cast<std::uint32_t>(hdr[0]) << 24) |
                               (static_cast<std::uint32_t>(hdr[1]) << 16) |
                               (static_cast<std::uint32_t>(hdr[2]) << 8)  |
                               static_cast<std::uint32_t>(hdr[3]);

    if (reply_len == 0) return std::vector<std::uint8_t>();

    std::vector<std::uint8_t> reply_buf(reply_len);
    got = 0;
    while (got < reply_len) {
        auto n = transport_->recv(reply_buf.data() + got, reply_len - got);
        if (!n) return n.error();
        if (*n == 0) return util::Error{24, "connection closed during reply"};
        got += *n;
    }

    // First byte is the reply opcode — skip it, return payload
    if (reply_len <= 1) return std::vector<std::uint8_t>();

    return std::vector<std::uint8_t>(reply_buf.begin() + 1, reply_buf.end());
}


