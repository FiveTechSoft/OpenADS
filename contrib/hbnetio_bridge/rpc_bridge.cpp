RpcClient::RpcClient(std::unique_ptr<ITransport> transport)
    : transport_(std::move(transport)) {}

RpcClient::~RpcClient() {
    if (transport_) {
        transport_->close();
    }
}


// -- RPC operations ----------------------------------------------------------

util::Result<std::vector<std::uint8_t>>
RpcClient::func_exec(const std::string& name,
                      const std::vector<std::vector<std::uint8_t>>& params) {
    // Build RpcCall frame:
    //   [u8 nameLen][name][packed params]
    std::vector<std::uint8_t> payload;
    std::uint8_t name_len = static_cast<std::uint8_t>(
        std::min(name.size(), static_cast<std::size_t>(255)));
    payload.push_back(name_len);
    payload.insert(payload.end(), name.begin(), name.begin() + name_len);

    auto packed_params = rpc_serial::pack_params(params);
    payload.insert(payload.end(), packed_params.begin(), packed_params.end());

    auto result = send_and_recv(
        static_cast<std::uint8_t>(RpcOpcode::Call),
        payload.data(), payload.size());

    if (!result) return result.error();
    return result;
}

