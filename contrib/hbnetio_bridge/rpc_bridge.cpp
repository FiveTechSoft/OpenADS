RpcBridge::RpcBridge()
    : start_time_(std::chrono::steady_clock::now()) {
    // Register built-in functions
    register_func("server_version", builtin_server_version);
    register_func("server_time",    builtin_server_time);
    register_func("server_uptime",  builtin_server_uptime);
}

RpcBridge::~RpcBridge() {
    // Close all active streams
    std::lock_guard<std::mutex> lock(mu_);
    for (auto& [id, stream] : streams_) {
        if (stream->active) {
            stream->active = false;
            if (stream->sender_thread.joinable()) {
                stream->sender_thread.join();
            }
        }
    }
    streams_.clear();
}


// -- Registration ------------------------------------------------------------

void RpcBridge::register_func(const std::string& name, RpcFunc func) {
    std::lock_guard<std::mutex> lock(mu_);
    funcs_[name] = std::move(func);
}

void RpcBridge::register_proc(const std::string& name, RpcProc proc) {
    std::lock_guard<std::mutex> lock(mu_);
    procs_[name] = std::move(proc);
}

void RpcBridge::unregister(const std::string& name) {
    std::lock_guard<std::mutex> lock(mu_);
    funcs_.erase(name);
    procs_.erase(name);
}

bool RpcBridge::func_exists(const std::string& name) const {
    std::lock_guard<std::mutex> lock(mu_);
    return funcs_.count(name) > 0 || procs_.count(name) > 0;
}


// -- RPC dispatch ------------------------------------------------------------

util::Result<std::vector<std::uint8_t>>
RpcBridge::handle_call(const std::string& func_name,
                       const std::vector<std::vector<std::uint8_t>>& params) {
    RpcFunc func;
    {
        std::lock_guard<std::mutex> lock(mu_);
        auto it = funcs_.find(func_name);
        if (it == funcs_.end()) {
            return util::Error{20, "function not found: " + func_name};
        }
        func = it->second;
    }

    return func(params);
}

util::Result<void>
RpcBridge::handle_proc(const std::string& proc_name,
                       const std::vector<std::vector<std::uint8_t>>& params) {
    RpcProc proc;
    {
        std::lock_guard<std::mutex> lock(mu_);
        auto it = procs_.find(proc_name);
        if (it == procs_.end()) {
            return util::Error{21, "procedure not found: " + proc_name};
        }
        proc = it->second;
    }

    return proc(params);
}

util::Result<void>
RpcBridge::handle_proc_w(const std::string& proc_name,
                          const std::vector<std::vector<std::uint8_t>>& params) {
    // Same as handle_proc but the caller expects a completion ack.
    // The ack is generated by the session dispatch after this returns.
    return handle_proc(proc_name, params);
}


// -- Stream management -------------------------------------------------------

std::uint32_t RpcBridge::next_stream_id() {
    return stream_seq_++;
}

util::Result<std::uint32_t>
RpcBridge::open_stream(const std::string& func_name,
                       const std::vector<std::vector<std::uint8_t>>& params,
                       StreamCallback callback) {
    std::uint32_t id = next_stream_id();

    auto info = std::make_unique<StreamInfo>();
    info->id = id;
    info->func_name = func_name;
    info->active = true;
    info->callback = std::move(callback);

    {
        std::lock_guard<std::mutex> lock(mu_);
        streams_[id] = std::move(info);
    }

    return id;
}

util::Result<void> RpcBridge::stream_send(std::uint32_t stream_id,
                                           const std::vector<std::uint8_t>& data) {
    std::lock_guard<std::mutex> lock(mu_);
    auto it = streams_.find(stream_id);
    if (it == streams_.end() || !it->second->active) {
        return util::Error{22, "stream not found or inactive"};
    }

    it->second->callback(stream_id, data);
    return util::Ok();
}

void RpcBridge::close_stream(std::uint32_t stream_id) {
    std::lock_guard<std::mutex> lock(mu_);
    auto it = streams_.find(stream_id);
    if (it != streams_.end()) {
        it->second->active = false;
        if (it->second->sender_thread.joinable()) {
            it->second->sender_thread.detach();
        }
        streams_.erase(it);
    }
}


// -- Built-in functions ------------------------------------------------------

util::Result<std::vector<std::uint8_t>>
RpcBridge::builtin_server_version(
    const std::vector<std::vector<std::uint8_t>>&) {
    const char* ver = OPENADS_VERSION_STR;
    return rpc_serial::pack_string(ver);
}

util::Result<std::vector<std::uint8_t>>
RpcBridge::builtin_server_time(
    const std::vector<std::vector<std::uint8_t>>&) {
    auto now = std::chrono::system_clock::now();
    auto epoch = now.time_since_epoch();
    auto secs = std::chrono::duration_cast<std::chrono::seconds>(epoch);
    return rpc_serial::pack_u64(static_cast<std::uint64_t>(secs.count()));
}

util::Result<std::vector<std::uint8_t>>
RpcBridge::builtin_server_uptime(
    const std::vector<std::vector<std::uint8_t>>&) {
    auto now = std::chrono::steady_clock::now();
    auto elapsed = std::chrono::duration_cast<std::chrono::seconds>(
        now - std::chrono::steady_clock::time_point{});
    return rpc_serial::pack_u64(static_cast<std::uint64_t>(elapsed.count()));
}


